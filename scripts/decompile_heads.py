"""Direction 2: decompile attention heads into library programs.

For every attention head, compare its attention pattern with patterns generated by
code (the same primitives as our op library):
  prev (t-1), prev2 (t-2), self (t), bos (0), induction (token after the latest earlier
  occurrence of the current token = prev_occ_next), dup (uniform over earlier copies of the
  current token), punct (latest punctuation/newline <= t), uniform (causal mean).
Fallback when a program has no target: attend to position 0 (the usual attention sink).

Per head: best-matching program and its match (1 - total variation, averaged over
positions), the loss change when its pattern is REPLACED by the program (value/output
weights kept), and the loss change when the head is mean-ablated. Then replace every head
whose match >= tau simultaneously and compare with mean-ablating the same heads.

    uv run python scripts/decompile_heads.py --model pythia-70m --data pile
"""
import argparse
import json
from pathlib import Path

import numpy as np
import torch
from transformers import AttentionInterface, AutoModelForCausalLM, AutoTokenizer

# ---- hookable attention: compute patterns ourselves, allow per-head overrides
ST = dict(capture=False, pats={}, zmean={}, override={}, ablate={}, P=None)


def hooked_attn(module, q, k, v, attention_mask, scaling=None, dropout=0.0, **kw):
    l = module.layer_idx
    T = q.shape[2]
    s = (q @ k.transpose(-1, -2)).float() * (scaling if scaling is not None else q.shape[-1] ** -0.5)
    s = s.masked_fill(torch.triu(torch.ones(T, T, dtype=torch.bool), 1), float("-inf"))
    w = s.softmax(-1).to(q.dtype)
    if ST["capture"]:
        ST["pats"][l] = w.detach()
    if l in ST["override"]:
        w = w.clone()
        for h, prog in ST["override"][l]:
            w[:, h] = ST["P"][prog]
    z = w @ v
    if ST["capture"]:
        ST["zmean"][l] = z.mean((0, 2), keepdim=True)
    if l in ST["ablate"]:
        z = z.clone()
        for h in ST["ablate"][l]:
            z[:, h] = ST["zmean"][l][:, h]
    return z.transpose(1, 2).contiguous(), None


AttentionInterface.register("hooked", hooked_attn)

PROGS = ["prev", "prev2", "self", "bos", "induction", "dup", "punct", "uniform"]


def program_patterns(tokens: torch.Tensor, punct_ids: torch.Tensor):
    """tokens (B,T) -> dict name -> (B,T,T) row-stochastic causal patterns."""
    B, T = tokens.shape
    idx = torch.arange(T)
    causal = idx[None, :] <= idx[:, None]  # (T,T) [t,j]
    pats = {}

    def onehot(j):  # j (B,T) target index
        return torch.nn.functional.one_hot(j.clamp(0, T - 1), T).float()

    pats["prev"] = onehot((idx - 1).clamp(min=0).expand(B, T))
    pats["prev2"] = onehot((idx - 2).clamp(min=0).expand(B, T))
    pats["self"] = onehot(idx.expand(B, T))
    pats["bos"] = onehot(torch.zeros(B, T, dtype=torch.long))
    same = (tokens[:, :, None] == tokens[:, None, :]) & (idx[None, None, :] < idx[None, :, None])  # j<t
    last = torch.where(same, idx[None, None, :], torch.full_like(same, -1, dtype=torch.long)).max(-1).values
    pats["induction"] = onehot(torch.where(last >= 0, last + 1, torch.zeros_like(last)))
    dup = same.float()
    has = dup.sum(-1, keepdim=True) > 0
    pats["dup"] = torch.where(has, dup / dup.sum(-1, keepdim=True).clamp(min=1), pats["bos"])
    isp = torch.isin(tokens, punct_ids)
    lp = torch.cummax(torch.where(isp, idx[None].expand(B, T), torch.full((B, T), -1)), 1).values
    pats["punct"] = onehot(lp.clamp(min=0))
    u = causal.float()
    pats["uniform"] = (u / u.sum(-1, keepdim=True)).expand(B, T, T)
    return pats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="pythia-70m")
    ap.add_argument("--data", default="pile")
    ap.add_argument("--n", type=int, default=48)
    ap.add_argument("--T", type=int, default=256)
    ap.add_argument("--tau", type=float, default=0.5)
    ap.add_argument("--out", default="runs/decompile")
    a = ap.parse_args()
    torch.set_grad_enabled(False)
    name = {"pythia-70m": "EleutherAI/pythia-70m", "pythia-160m": "EleutherAI/pythia-160m",
            "pythia-410m": "EleutherAI/pythia-410m"}.get(a.model, a.model)
    tok = AutoTokenizer.from_pretrained(name)
    model = AutoModelForCausalLM.from_pretrained(name, attn_implementation="hooked",
                                                 dtype=torch.float32).eval()
    if a.data == "pile":
        docs = json.loads(Path("data/pile/valid_docs.json").read_text())
    else:
        docs = json.loads(Path("data/tinystories/valid_stories.json").read_text())
    eos = tok.eos_token_id
    ids = []
    for d in docs:
        ids += [eos] + tok(d)["input_ids"]
    tokens = torch.tensor([ids[i * a.T:(i + 1) * a.T] for i in range(a.n)])
    punct = [i for s_, i in tok.get_vocab().items() if any(c in s_ for c in ".,;:!?\n") or "Ċ" in s_]
    ST["P"] = program_patterns(tokens, torch.tensor(punct))
    cfg = model.config
    L, H = cfg.num_hidden_layers, cfg.num_attention_heads

    def loss(override=None, ablate=None):
        ST["override"], ST["ablate"] = override or {}, ablate or {}
        out = model(tokens, labels=tokens).loss.item()
        ST["override"], ST["ablate"] = {}, {}
        return out

    ST["capture"] = True
    base = loss()
    ST["capture"] = False
    cache = {f"pat{l}": ST["pats"][l] for l in range(L)}

    def group(d):
        g = {}
        for (l, h), v in d.items():
            g.setdefault(l, []).append((h, v) if v is not None else h)
        return g

    def replace_pattern(heads_progs):
        return loss(override=group(heads_progs))

    def mean_ablate(heads):
        return loss(ablate=group({k: None for k in heads}))

    pats = ST["P"]
    results = []
    for l in range(L):
        P = cache[f"pat{l}"]  # (B,H,T,T)
        for h in range(H):
            ph = P[:, h]
            match = {p: float(1 - 0.5 * (ph - pats[p]).abs().sum(-1)[:, 1:].mean()) for p in PROGS}
            best = max(match, key=match.get)
            d_rep = replace_pattern({(l, h): best}) - base
            d_abl = mean_ablate([(l, h)]) - base
            results.append(dict(layer=l, head=h, prog=best, match=round(match[best], 3),
                                d_replace=round(d_rep, 4), d_ablate=round(d_abl, 4)))
        print(f"layer {l} done", flush=True)

    good = [(r["layer"], r["head"]) for r in results if r["match"] >= a.tau]
    progs = {(r["layer"], r["head"]): r["prog"] for r in results}
    all_rep = replace_pattern({k: progs[k] for k in good}) - base if good else 0.0
    all_abl = mean_ablate(good) - base if good else 0.0
    every_rep = replace_pattern(progs) - base
    every_abl = mean_ablate(list(progs)) - base
    counts = {p: sum(r["prog"] == p and r["match"] >= a.tau for r in results) for p in PROGS}
    summary = dict(model=a.model, base_loss=round(base, 4), heads=L * H, tau=a.tau,
                   n_matched=len(good), matched_by_prog=counts,
                   replace_matched_dloss=round(all_rep, 4), ablate_matched_dloss=round(all_abl, 4),
                   replace_all_dloss=round(every_rep, 4), ablate_all_dloss=round(every_abl, 4),
                   frac_heads_small_damage=round(np.mean([r["d_replace"] < 0.01 for r in results]), 3),
                   frac_heads_replace_beats_ablate=round(np.mean([r["d_replace"] < r["d_ablate"] for r in results]), 3))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{a.model}.json").write_text(json.dumps(dict(summary=summary, heads=results), indent=2))
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
